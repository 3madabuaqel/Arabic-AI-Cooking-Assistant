def health_check():
    return {"status": "ok"}

@app.get("/search", response_model=List[RecipeResponse], tags=["Search"])
def search(
    query: str = Query(..., description="The search query in Arabic"),
    mode: str = Query("auto", description="Search mode: 'auto', 'overview', 'ingredients', or 'title'"),
    top_k: int = Query(5, description="Number of results to return", ge=1, le=20)
):
    """
    Search for recipes using AI.
    
    - **query**: The search query (e.g., 'لحمة', 'بدي كفتة', 'صوص')
    - **mode**: 
        - `auto`: Automatically determine the mode based on the query
        - `overview`: General semantic search based on recipe description, title, and tags
        - `ingredients`: Fridge search based on available ingredients
        - `title`: Specific recipe name search
    - **top_k**: Number of results to return (default 5)
    """
    valid_modes = ["auto", "overview", "ingredients", "title"]
    if mode not in valid_modes:
        raise HTTPException(status_code=400, detail=f"Invalid mode. Must be one of: {', '.join(valid_modes)}")
    
    try:
        results = search_recipes(query=query, mode=mode, top_k=top_k)
        return results
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"An error occurred during search: {str(e)}")

@app.post("/modify_recipe", response_model=ModifyRecipeResponse, tags=["AI Features"])
def modify_recipe(request: ModifyRecipeRequest):
    """
    Modify an existing recipe using Gemini AI based on user instructions.
    
    - **recipe_data**: The original recipe data (title, description, ingredients, instructions)
    - **user_instruction**: The user's request (e.g., "نقص الكمية للنص", "بدي اياها صحية بدون زيت")
    """
    try:
        modified_text = modify_recipe_with_gemini(request.recipe_data, request.user_instruction)
        return {"modified_text": modified_text}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"An error occurred: {str(e)}")

@app.get("/search_and_guide", response_model=SearchAndGuideResponse, tags=["AI Features"])
def search_and_guide(
    query: str = Query(..., description="The search query in Arabic"),
):
    """
    Searches for the closest recipe and returns a step-by-step guide generated by Gemini.
    """
    try:
        results = search_recipes(query=query, mode="auto", top_k=1)
        if not results:
            return {"recipe": None, "guide_text": "عذراً، لم أتمكن من العثور على وصفة مطابقة لطلبك."}
            
        top_recipe = results[0]
        guide_text = guide_recipe_with_gemini(top_recipe)
        
        return {"recipe": top_recipe, "guide_text": guide_text}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"An error occurred: {str(e)}")

